import pandas as pd

# ============================================================
# 데이터 불러오기
# ============================================================

df = pd.read_csv("04-01_고장의_진행_구조_고장사례_128_260903_Question_1.csv")

print("전체 사례 수:", len(df))

# ============================================================
# 실습 1 - P-F 간격과 점검 주기
# ============================================================

리드타임 = 20

# Step 1. 대응 가능 여부 판정
df["대응가능"] = df["PF간격_일"] > 리드타임

print("\n[실습 1 - Step 1]")
print(df[["사례ID", "설비", "PF간격_일", "대응가능"]])

# Step 2. 대응 불가 사례 찾기
대응불가 = df[df["대응가능"] == False]

print("\n[실습 1 - Step 2]")
print(대응불가["사례ID"])

# Step 3. 권장 점검 주기 계산
df["권장점검주기_일"] = df["PF간격_일"] / 2

print("\n[실습 1 - Step 3]")
print(df[["사례ID", "설비", "PF간격_일", "권장점검주기_일", "대응가능"]])

# Step 4. 저장 주기가 절반 규칙을 만족하는지 확인
df["저장주기_일"] = df["저장주기_분"] / (60 * 24)

df["저장주기_적정"] = (
    (df["데이터저장여부"] == "Y")
    & (df["저장주기_일"] <= df["권장점검주기_일"])
)

저장주기적정 = df[df["저장주기_적정"] == True]

print("\n[실습 1 - Step 4]")
print(저장주기적정["사례ID"])

# ============================================================
# 실습 2 - 고장의 예측 가능성 분류
# ============================================================

# Step 1. 판정 규칙 만들기
def 고장판정(row, 리드타임):
    if row["손상형태"] == "과부하 파단" or row["손상형태"] == "이물":
        return "물리적 돌발"
    elif row["PF간격_일"] <= 리드타임:
        return "간격 부족형"
    elif row["데이터저장여부"] != "Y":
        return "측정 부재형"
    else:
        return "예측 가능형"

# Step 2. 케이스 A와 케이스 B 판정
df["케이스A_판정"] = df.apply(lambda row: 고장판정(row, 7), axis=1)
df["케이스B_판정"] = df.apply(lambda row: 고장판정(row, 30), axis=1)

print("\n[실습 2 - Step 2]")
print(df[[
    "사례ID",
    "설비",
    "손상형태",
    "PF간격_일",
    "데이터저장여부",
    "케이스A_판정",
    "케이스B_판정"
]])

# Step 3. 리드타임 때문에 판정이 바뀐 사례 찾기
판정변경 = df[df["케이스A_판정"] != df["케이스B_판정"]]

print("\n[실습 2 - Step 3]")
print(판정변경["사례ID"])

print("이유: 리드타임이 길어지면 P-F 간격 안에 필요한 대응을 완료하기 어려워질 수 있기 때문입니다.")

# Step 4. 예측 가능형의 목표 조기 경보 시점 계산
예측가능_A = df[df["케이스A_판정"] == "예측 가능형"].copy()

예측가능_A["목표경보_일전"] = (
    (예측가능_A["PF간격_일"] * 0.5).round().astype(int)
)

print("\n[실습 2 - Step 4]")
print(예측가능_A[["사례ID", "설비", "PF간격_일", "목표경보_일전"]])

# Step 5. 예측 불가 사례의 대응 방향 정하기
예측불가_B = df[df["케이스B_판정"] != "예측 가능형"].copy()

대응방향표 = {
    "물리적 돌발": "이중화 또는 정기 교체",
    "간격 부족형": "보호 로직 또는 자동 정지",
    "측정 부재형": "계측 개선 또는 저장 주기 조정"
}

예측불가_B["대응방향"] = 예측불가_B["케이스B_판정"].map(대응방향표)

print("\n[실습 2 - Step 5]")
print(예측불가_B[["사례ID", "설비", "케이스B_판정", "대응방향"]])

