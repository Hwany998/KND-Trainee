import pandas as pd
import glob

# ============================================================
# 데이터 불러오기
# ============================================================

csv_file = glob.glob("*.csv")[0]
df = pd.read_csv(csv_file)
print("전체 사례 수:", len(df))

# ============================================================
# 실습 1 - P-F 간격과 점검 주기
# ============================================================

리드타임 = 20

# ------------------------------------------------------------
# Step 1. 대응 가능 여부 판정
# ------------------------------------------------------------

df["대응가능"] = df["PF간격_일"] > 리드타임

print("\n[실습 1 - Step 1] 대응 가능 여부")
print(df[["사례ID", "설비", "PF간격_일", "대응가능"]])

# ------------------------------------------------------------
# Step 2. 대응 불가 사례 찾기
# ------------------------------------------------------------

대응불가 = df[df["대응가능"] == False]

print("\n[실습 1 - Step 2] 대응 불가 사례ID")
print(대응불가["사례ID"].tolist())

# ------------------------------------------------------------
# Step 3. 권장 점검 주기 계산
# ------------------------------------------------------------

df["권장점검주기_일"] = df["PF간격_일"] / 2

print("\n[실습 1 - Step 3] 권장 점검 주기")
print(df[["사례ID", "설비", "PF간격_일", "권장점검주기_일", "대응가능"]])

# ------------------------------------------------------------
# Step 4. 저장 주기가 절반 규칙을 만족하는지 확인
# ------------------------------------------------------------

# 분(minute)을 일(day)로 변환: 1일 = 24 * 60 = 1440분
df["저장주기_일"] = df["저장주기_분"] / (24 * 60)

df["저장주기_적정"] = (
    (df["데이터저장여부"] == "Y")
    & (df["저장주기_일"] <= df["권장점검주기_일"])
)

저장주기_적정_사례 = df[df["저장주기_적정"] == True]

print("\n[실습 1 - Step 4] 저장 주기가 적정한 사례ID")
print(저장주기_적정_사례["사례ID"].tolist())

# ============================================================
# 실습 2 - 고장의 예측 가능성 분류
# ============================================================

# ------------------------------------------------------------
# Step 1. 판정 규칙 만들기
# ------------------------------------------------------------

def 예측가능성_판정(row, 리드타임):
    if row["손상형태"] in ["과부하 파단", "이물"]:
        return "물리적 돌발"
    elif row["PF간격_일"] <= 리드타임:
        return "간격 부족형"
    elif row["데이터저장여부"] != "Y":
        return "측정 부재형"
    else:
        return "예측 가능형"

# ------------------------------------------------------------
# Step 2. 케이스 A와 케이스 B 판정
# ------------------------------------------------------------

df["케이스A_판정"] = df.apply(lambda row: 예측가능성_판정(row, 7), axis=1)
df["케이스B_판정"] = df.apply(lambda row: 예측가능성_판정(row, 30), axis=1)

print("\n[실습 2 - Step 2] 케이스 A/B 판정")
print(df[[
    "사례ID", "설비", "손상형태", "PF간격_일", "데이터저장여부",
    "케이스A_판정", "케이스B_판정"
]])

# ------------------------------------------------------------
# Step 3. 리드타임 때문에 판정이 바뀐 사례 찾기
# ------------------------------------------------------------

판정변경 = df[df["케이스A_판정"] != df["케이스B_판정"]]

print("\n[실습 2 - Step 3] 판정이 바뀐 사례ID")
print(판정변경["사례ID"].tolist())

# 추가 질문 답:
# 리드타임이 길어지면 고장에 대응하기 위해 필요한 시간이 늘어나므로,
# 같은 P-F 간격이라도 리드타임보다 짧거나 같아질 수 있습니다.
# 이 경우 미리 이상을 감지하더라도 실제 정비를 완료하기 전에 기능 고장(F)에
# 도달할 수 있기 때문에 "예측 가능형"에서 "간격 부족형"으로 바뀔 수 있습니다.

# ------------------------------------------------------------
# Step 4. 예측 가능형의 목표 조기 경보 시점 계산
# ------------------------------------------------------------

예측가능_A = df[df["케이스A_판정"] == "예측 가능형"].copy()
예측가능_A["목표경보_일전"] = (예측가능_A["PF간격_일"] * 0.5).round().astype(int)

print("\n[실습 2 - Step 4] 목표 조기 경보 시점")
print(예측가능_A[["사례ID", "설비", "PF간격_일", "목표경보_일전"]])

# ------------------------------------------------------------
# Step 5. 예측 불가 사례의 대응 방향 정하기
# ------------------------------------------------------------

예측불가_B = df[df["케이스B_판정"] != "예측 가능형"].copy()

대응방향_매핑 = {
    "물리적 돌발": "이중화 또는 정기 교체",
    "간격 부족형": "보호 로직 또는 자동 정지",
    "측정 부재형": "계측 개선 또는 저장 주기 조정"
}

예측불가_B["대응방향"] = 예측불가_B["케이스B_판정"].map(대응방향_매핑)

print("\n[실습 2 - Step 5] 예측 불가 사례 대응 방향")
print(예측불가_B[["사례ID", "설비", "케이스B_판정", "대응방향"]])

