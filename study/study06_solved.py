# 상대적인 크기로 결정되기 때문입니다. 같은 고장도 리드타임이 짧으면 대응할 시간이
# 충분하지만, 리드타임이 길어지면 P-F 간격 안에 조치를 끝낼 수 없어 간격 부족형이
